// Command gen writes components_gen.go from the component VERSION files.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// componentPaths maps each ADR-0015 component to its directory.
var componentPaths = map[string]string{
	"platform":        ".",
	"api":             "api",
	"server":          "cmd/server",
	"worker":          "cmd/worker",
	"agent":           "cmd/agent",
	"reposerver":      "cmd/reposerver",
	"cli":             "cmd/dbr2",
	"web":             "web",
	"agent-protocol":  "proto/agent",
	"manifest-schema": "internal/manifest",
	"db-schema":       "db",
	"deployment":      "deployments",
}

func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("out", "components_gen.go", "output file")
	flag.Parse()

	names := make([]string, 0, len(componentPaths))
	for n := range componentPaths {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/version/gen from the component VERSION files. DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\npackage version\n\n")
	b.WriteString("// components maps each component to MAJOR.MINOR.BUGFIX from its VERSION file.\n")
	b.WriteString("var components = map[string]string{\n")
	for _, n := range names {
		raw, err := os.ReadFile(filepath.Join(*root, componentPaths[n], "VERSION"))
		if err != nil {
			log.Fatalf("read VERSION for %s: %v", n, err)
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", n, strings.TrimSpace(string(raw)))
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
